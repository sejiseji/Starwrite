def normalize_language(value: object) -> Language:
    return "ja" if value == "ja" else "en"


def next_language(language: Language) -> Language:
    return "ja" if language == "en" else "en"


def constellation_name(constellation: Constellation, language: Language) -> str:
    if language == "ja":
        return CONSTELLATION_NAMES_JA.get(constellation.id, constellation.name)
    return constellation.name


def constellation_sort_key(constellation: Constellation, language: Language) -> tuple[str, str]:
    if language == "ja":
        return (_japanese_sort_text(constellation_name(constellation, language).removesuffix("座")), constellation.id)
    return (constellation.name.casefold(), constellation.id)


def star_sort_key(star_id: int, english_name: str, language: Language) -> tuple[str, int]:
    name = star_name(star_id, english_name, language)
    if language == "ja":
        return (_japanese_sort_text(name), star_id)
    return (english_name.casefold(), star_id)


def sky_feature_sort_key(feature: Asterism | SkyPath, language: Language) -> tuple[str, str]:
    name = sky_feature_name(feature, language)
    if language == "ja":
        return (_japanese_sort_text(name), feature.id)
    return (feature.name.casefold(), feature.id)


def _japanese_sort_text(text: str) -> str:
    converted = []
    for char in text:
        codepoint = ord(char)
        if 0x30A1 <= codepoint <= 0x30F6:
            converted.append(chr(codepoint - 0x60))
        else:
            converted.append(char)
    return "".join(converted)


def meteor_event_name(event: MeteorShowerEvent, language: Language) -> str:
    if language == "ja":
        return METEOR_EVENT_NAMES_JA.get(event.id.split("-", 1)[0], event.name)
    return event.name


def sky_event_name(event: SkyEvent, language: Language) -> str:
    if isinstance(event, LunarEclipseEvent):
        if language == "ja":
            return "皆既月食" if event.eclipse_type == "total" else "部分月食"
        return event.name
    return meteor_event_name(event, language)


