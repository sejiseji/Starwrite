def validate_constellation_line_reference() -> None:
    assert len(CONSTELLATION_LINE_EDGES_HIP) == 88
    assert set(CONSTELLATION_LINE_EDGES_HIP) == set(CONSTELLATION_MAIN_STAR_IDS_HIP)
    assert set(CONSTELLATION_LINE_POLYLINES_HIP) == set(CONSTELLATION_LINE_EDGES_HIP)
    for constellation_id, edges in CONSTELLATION_LINE_EDGES_HIP.items():
        allowed = set(CONSTELLATION_MAIN_STAR_IDS_HIP[constellation_id])
        seen: set[tuple[int, int]] = set()
        assert edges
        assert allowed == {star_id for edge in edges for star_id in edge}
        for a, b in edges:
            assert a != b
            assert a in allowed and b in allowed
            normalized = (a, b) if a < b else (b, a)
            assert normalized not in seen
            seen.add(normalized)
